type vResultTyped struct {
	Status   status    `json:"status"`
	Mistakes []problem `json:"mistakes"`
}
type validateResult struct {
	Product   vResultTyped  `json:"product"`
	Artifacts *vResultTyped `json:"artifacts,omitempty"`
}

type problem struct {
	Key      string `json:"key"`
	Message  string `json:"message"`
	Expected string `json:"expected,omitempty"`
	Actual   string `json:"actual,omitempty"`
	Line     string `json:"line,omitempty"`
}

type validateCmd struct {
	log    *slog.Logger
	config *config.Config
}

func newValidateCmd(cfg *config.Config, log *slog.Logger) *validateCmd {
	return &validateCmd{
		config: cfg,
		log:    log.With("cmd", "validate"),
	}
}

type status string

const (
	statusOK status = "OK"
	statusKO status = "KO"
)

func (r vResultTyped) ok() bool { return r.Status == statusOK }

var (
	errInvalidProductCard = errors.New("product card is invalid")
	errInvalidArtifacts   = errors.New("artifact file is invalid")
)

// productSchemaPath is where the server publishes the JSON schema of the product cards.
const productSchemaPath = "/registry/json-schema"

const artifactsSchemaHelp = "https://local-registry.nivekaa.com/schemas/artifacts.schema.json"

func newValidateProductCommand() *cobra.Command {
	cmd := cobra.Command{
		Use:   "validate",
		Short: "Validate a product card (Registry.yaml)",
		Long:  "",
		Example: `lrctl validate /path/to/registry.yaml \
						--artifacts=/path/to/artifacts.json
		`,
		Args: withArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			p := logging.From(cmd.Context())
			cfg := config.From(cmd.Context())
			if cfg == nil {
				return errors.New("the configuration is not loaded")
			}

			this := newValidateCmd(cfg, p.Logger())

			productFile := args[0]
			artifactsFile, _ := cmd.Flags().GetString("artifacts")

			res, err := this.runValidateProduct(cmd.Context(), productFile, artifactsFile)
			if err != nil {
				return err
			}
			return this.displayResult(res, p)
		},
	}

	cmd.Flags().String("artifacts", "", "The artifacts file generated by GoReleaser of manually wrote. E.g: --artifacts=/path/to/dist/artifacts.json")

	return &cmd
}

type section struct {
	title  string
	result vResultTyped
	err    error
}

func (v *validateCmd) printSection(w io.Writer, sect section) error {
	if sect.result.ok() {
		return v.printText(w, "STATUS: %s, Message: the %s is valid", sect.result.Status, sect.title)
	}

	err := errors.Join(
		v.printText(w, "STATUS: %s, Error: %v", sect.result.Status, sect.err),
		v.printText(w, ""),
	)
	// The tabwriter buffers until Flush, which returns the write error.
	tabw := tabwriter.NewWriter(w, 0, 0, 2, ' ', 0)
	_ = v.printText(tabw, "NO\tFIELD\tMISTAKE")
	for idx, m := range sect.result.Mistakes {
		_ = v.printText(tabw, "%d\t%s\t%s", idx+1, m.Key, m.Message)
	}
	return errors.Join(err, tabw.Flush())
}

// displayResult prints res, and returns an error when a file is invalid: in text and in JSON,
// so that a CI fails on an invalid card whatever the output.
func (v *validateCmd) displayResult(res *validateResult, p *logging.Printer) error {
	sections := []section{
		{"PRODUCT CARD", res.Product, errInvalidProductCard},
	}
	if res.Artifacts != nil {
		sections = append(sections, section{"ARTIFACT FILE", *res.Artifacts, errInvalidArtifacts})
	}

	var validationErrors []error
	for _, sect := range sections {
		if !sect.result.ok() {
			validationErrors = append(validationErrors, sect.err)
		}
	}

	displayErr := p.Result(res, func(w io.Writer) error {
		multi := len(sections) > 1
		var errs []error
		for _, s := range sections {
			if multi && !s.result.ok() {
				errs = append(errs,
					v.printText(w, "--------------------------- [ %s ] ---------------------------", s.title),
					v.printText(w, ""))
			}
			errs = append(errs, v.printSection(w, s))
		}
		return errors.Join(errs...)
	})

	return errors.Join(displayErr, errors.Join(validationErrors...))
}

func (v *validateCmd) printText(w io.Writer, format string, args ...any) error {
	_, err := fmt.Fprintf(w, format+"\n", args...)
	return err
}

// runValidateProduct returns an error only when the files cannot be checked (the schema cannot
// be fetched): an invalid file is a KO status with its mistakes.
func (v *validateCmd) runValidateProduct(ctx context.Context, productFile, artifactsFile string) (*validateResult, error) {
	newVResult := func(problems []problem) vResultTyped {
		if problems == nil {
			problems = []problem{}
		}
		st := statusOK
		if len(problems) > 0 {
			st = statusKO
		}
		return vResultTyped{Status: st, Mistakes: problems}
	}

	problems, err := v.validateProductFile(ctx, productFile)
	if err != nil {
		return nil, err
	}
	res := &validateResult{Product: newVResult(problems)}
	if artifactsFile != "" {
		a := newVResult(v.validateArtifacts(ctx, artifactsFile))
		res.Artifacts = &a
	}
	return res, nil
}

// validateProductFile reads the card before fetching the schema: a missing or broken file is
// reported without a request to the server.
func (v *validateCmd) validateProductFile(ctx context.Context, productFile string) ([]problem, error) {
	log := v.log.With("step", "product")
	documentJsonBytes, err := yamlToJSON(productFile)
	if err != nil {
		log.DebugContext(ctx, "conversion", "file", productFile, "err", err)
		return []problem{{Message: err.Error()}}, nil
	}

	schemaSpec, err := fetchProductSchemaSpec(ctx, v.config, log)
	if err != nil {
		return nil, err
	}
	return validateSchema(ctx, log, schemaSpec, documentJsonBytes), nil
}

func (v *validateCmd) validateArtifacts(ctx context.Context, artifactsFile string) []problem {
	log := v.log.With("step", "artifacts")

	documentJsonBytes, err := os.ReadFile(artifactsFile)
	if err != nil {
		log.DebugContext(ctx, "read", "file", artifactsFile, "err", err)
		return []problem{
			{Message: fmt.Sprintf("error while reading %s: %v", artifactsFile, err)},
		}
	}

	problems := validateSchema(ctx, log, schema.GrArtifactsSchemaJSON, documentJsonBytes)
	if len(problems) > 0 && problems[0].Key == "" {
		problems = append(problems, problem{Key: "Help", Message: artifactsSchemaHelp})
	}
	return problems
}

// validateSchema returns the mistakes of document against schemaSpec, or a problem without a
// key when the validation cannot run (schema or document is not JSON).
func validateSchema(ctx context.Context, log *slog.Logger, schemaSpec, document []byte) []problem {
	schemaLoader := gojsonschema.NewBytesLoader(schemaSpec)
	documentLoader := gojsonschema.NewBytesLoader(document)

	result, err := gojsonschema.Validate(schemaLoader, documentLoader)
	if err != nil {
		log.DebugContext(ctx, "validation", "err", err)
		return []problem{
			{Message: "#1: unable to valide schema"},
			{Key: "Raw", Message: err.Error()},
		}
	}
	if result.Valid() {
		return nil
	}
	errs := make([]problem, 0, len(result.Errors()))
	for _, desc := range result.Errors() {
		errs = append(errs, problem{
			Key:     desc.Field(),
			Message: desc.Description(),
		})
	}
	log.DebugContext(ctx, "validation", "mistakes", arrayResultErrorToSingleError(result.Errors()))
	return errs
}

func arrayResultErrorToSingleError(errs []gojsonschema.ResultError) string {
	var errsStr strings.Builder
	for _, re := range errs {
		errsStr.WriteString(re.Description() + "; ")
	}
	return errsStr.String()
}

func yamlToJSON(yamlFile string) ([]byte, error) {
	if ext := filepath.Ext(yamlFile); !slices.Contains([]string{".yaml", ".yml"}, ext) {
		return nil, fmt.Errorf("%s is not a yaml file (ext=%s)", yamlFile, ext)
	}

	data, err := os.ReadFile(yamlFile)
	if err != nil {
		return nil, fmt.Errorf("error while reading %s: %w", yamlFile, err)
	}

	var doc any
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("parse yaml %s: %w", yamlFile, err)
	}
	out, err := json.MarshalIndent(doc, "", " ")
	if err != nil {
		return nil, fmt.Errorf("parse json : %w", err)
	}

	return out, nil
}

// fetchProductSchemaSpec fails on anything but a 2xx: the body of an error page is not the
// schema, and validating against it would accept any card.
func fetchProductSchemaSpec(ctx context.Context, cfg *config.Config, log *slog.Logger) ([]byte, error) {
	url := cfg.Server.BaseUrl + productSchemaPath
	start := time.Now()
	// A response from the cache has no Request: log with url, not resp.Request.
	resp, err := cfg.HttpClient().Get(ctx, productSchemaPath, nil)
	if err != nil {
		var ce *httpclient.ClientError
		if errors.As(err, &ce) && ce.Message != "" {
			err = errors.New(ce.Message)
		}
		log.DebugContext(ctx, "request", "method", http.MethodGet, "url", url, "err", err)
		return nil, fmt.Errorf("fetch the product schema: %w", err)
	}
	defer resp.Body.Close()

	body, err := io.ReadAll(resp.Body)
	log.DebugContext(ctx, "request", "method", http.MethodGet, "url", url,
		"status", resp.StatusCode, "duration", time.Since(start))
	if err != nil {
		return nil, fmt.Errorf("fetch the product schema from %s: %w", url, err)
	}
	if !httpclient.IsSuccess(resp) {
		return nil, fmt.Errorf("fetch the product schema from %s: %s", url, resp.Status)
	}
	return body, nil
}
