type vResultTyped struct {
	Status   status    `json:"status"`
	Mistakes []problem `json:"mistakes"`
}
type validateResult struct {
	Product   vResultTyped  `json:"product"`
	Artifacts *vResultTyped `json:"Artifacts"`
}

type problem struct {
	Key      string `json:"key"`
	Message  string `json:"message"`
	Expected string `json:"expected"`
	Actual   string `json:"actual"`
	Line     string `json:"line"`
}

type validateCmd struct {
	log    *slog.Logger
	config *config.Config
}

func new(cfg *config.Config, log *slog.Logger) *validateCmd {
	return &validateCmd{
		config: cfg,
		log:    log,
	}
}

var exitCode = 0

type status string

const (
	statusOK status = "OK"
	statusKO status = "KO"
)

func (r vResultTyped) ok() bool { return r.Status == statusOK }

var (
	errInvalidProductCard = errors.New("product card is invalid")
	errInvalidArtifacts   = errors.New("artifact file is invalid")
)

func newValidateProductCommand() *cobra.Command {
	cmd := cobra.Command{
		Use:   "validate",
		Short: "Validate a product card (Registry.yaml)",
		Long:  "",
		Example: `lrctl validate /path/to/registry.yaml \
						--artifacts=/path/to/artifacts.json
		`,
		Args: withArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			p := logging.From(cmd.Context())
			cfg := config.From(cmd.Context())
			if cfg == nil {
				return errors.New("the configuration is not loaded")
			}

			this := new(cfg, p.Logger())

			productFile := args[0]
			artifactsFile, _ := cmd.Flags().GetString("artifacts")

			res := this.runValidateProduct(cmd.Context(), productFile, artifactsFile)

			return this.displayResult(res, p)
		},
	}

	cmd.Flags().String("artifacts", "", "The artifacts file generated by GoReleaser of manually wrote. E.g: --artifacts=/path/to/dist/artifacts.json")
	cmd.Flags().IntVar(&exitCode, "exit-code", 0, "the existing code for CI. Default is 0")

	return &cmd
}

type section struct {
	title  string
	result vResultTyped
	err    error
}

func (v validateCmd) printSection(w io.Writer, sect section) error {
	if sect.result.ok() {
		v.printText(w, "STATUS: %s, Message: the %s is valid", sect.result.Status, sect.title)
		return nil
	}

	v.printText(w, "STATUS: %s, Error: %v", sect.result.Status, sect.err)
	v.printText(w, "")
	tabw := tabwriter.NewWriter(w, 0, 0, 2, ' ', 0)
	v.printText(tabw, "NO\tFIELD\tMISTAKE")
	for idx, m := range sect.result.Mistakes {
		v.printText(tabw, "%d\t%s\t%s", idx+1, m.Key, m.Message)
	}
	return tabw.Flush()
}

func (v validateCmd) displayResult(toPrint *validateResult, p *logging.Printer) error {
	return p.Result(toPrint, func(w io.Writer) error {

		sections := []section{
			{"PRODUCT CARD", toPrint.Product, errInvalidProductCard},
		}

		if toPrint.Artifacts != nil {
			sections = append(sections, section{"ARTIFACT FILE", *toPrint.Artifacts, errInvalidArtifacts})
		}

		var validationErrors []error
		for _, sect := range sections {
			if !sect.result.ok() {
				validationErrors = append(validationErrors, sect.err)
			}
		}

		displayErr := p.Result(toPrint, func(w io.Writer) error {
			multi := len(sections) > 1
			var errs []error
			for _, s := range sections {
				if multi && !s.result.ok() {
					v.printText(w, "--------------------------- [ %s ] ---------------------------", s.title)
					v.printText(w, "")
				}
				errs = append(errs, v.printSection(w, s))
			}
			return errors.Join(errs...)
		})

		return errors.Join(displayErr, errors.Join(validationErrors...))
	})
}

func (v validateCmd) printText(w io.Writer, format string, args ...any) {
	if format == "" {
		_, _ = fmt.Fprintln(w)
	} else {
		_, _ = fmt.Fprintf(w, format, args...)
		_, _ = fmt.Fprintln(w)
	}

}

func (v *validateCmd) runValidateProduct(context context.Context, productFile, artifactsFile string) *validateResult {

	newVResult := func(problems []problem) vResultTyped {
		if problems == nil {
			problems = []problem{}
		}
		st := statusOK
		if len(problems) > 0 {
			st = statusKO
		}
		return vResultTyped{Status: st, Mistakes: problems}
	}
	res := &validateResult{
		Product: newVResult(v.validateProductFile(context, productFile)),
	}
	if artifactsFile != "" {
		a := newVResult(v.validateArtifacts(context, artifactsFile))
		res.Artifacts = &a
	}
	return res
}

func (v *validateCmd) validateProductFile(context context.Context, productFile string) []problem {
	schemaSpec, err := fetchProductSchemaSpec(context, v.config, v.log)
	if err != nil {
		return []problem{
			{Message: err.Error()},
		}
	}
	documentJsonBytes, err := yamlToJSON(productFile)
	relog := v.log.With("validate", "Yaml to JSON")
	if err != nil {
		relog.DebugContext(context, "error", err)
		return []problem{
			{Message: err.Error()},
		}
	}
	schemaLoader := gojsonschema.NewBytesLoader(schemaSpec)
	documentLoader := gojsonschema.NewBytesLoader(documentJsonBytes)

	result, err := gojsonschema.Validate(schemaLoader, documentLoader)
	if err != nil {
		relog.DebugContext(context, "error", err)
		return []problem{
			{Message: "#1: unable to valide schema"},
			{Key: "Raw", Message: err.Error()},
		}
	}
	if !result.Valid() {
		errs := make([]problem, 0, len(result.Errors()))
		for _, desc := range result.Errors() {
			errs = append(errs, problem{
				Key:     desc.Field(),
				Message: desc.Description(),
			})
		}
		relog.DebugContext(context, "errors", result.Errors())
		return errs
	}
	return nil
}

func (v *validateCmd) validateArtifacts(context context.Context, artifactsFile string) []problem {

	relog := v.log.With("validate", "artifacts")

	documentJsonBytes, err := os.ReadFile(artifactsFile)
	if err != nil {
		relog.DebugContext(context, "error", err)
		return []problem{
			{Message: fmt.Sprintf("error while reading %s: %w", artifactsFile, err)},
		}
	}

	schemaLoader := gojsonschema.NewReferenceLoader("https://raw.githubusercontent.com/goreleaser/goreleaser/v2.19.0/www/static/schema.json")
	documentLoader := gojsonschema.NewBytesLoader(documentJsonBytes)

	result, err := gojsonschema.Validate(schemaLoader, documentLoader)
	if err != nil {
		relog.DebugContext(context, "error", err)
		return []problem{
			{Message: "#1: unable to valide schema"},
			{Key: "Raw", Message: err.Error()},
			{Key: "Help", Message: "https://raw.githubusercontent.com/goreleaser/goreleaser/v2.19.0/www/static/schema.json"},
		}
	}
	if !result.Valid() {
		errs := make([]problem, 0, len(result.Errors()))
		for _, desc := range result.Errors() {
			errs = append(errs, problem{
				Key:     desc.Field(),
				Message: desc.Description(),
			})
		}
		relog.DebugContext(context, "errors", result.Errors())
		return errs
	}
	return nil
}

func yamlToJSON(yamlFile string) ([]byte, error) {
	if ext := filepath.Ext(yamlFile); !slices.Contains([]string{".yaml", ".yml"}, ext) {
		return nil, fmt.Errorf("%s is not a yaml file (ext=%s)", yamlFile, ext)
	}

	data, err := os.ReadFile(yamlFile)
	if err != nil {
		return nil, fmt.Errorf("error while reading %s: %w", yamlFile, err)
	}

	var doc any
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("parse yaml %s: %w", yamlFile, err)
	}
	out, err := json.MarshalIndent(doc, "", " ")
	if err != nil {
		return nil, fmt.Errorf("parse json : %w", err)
	}

	return out, nil
}

func fetchProductSchemaSpec(ctx context.Context, cfg *config.Config, log *slog.Logger) ([]byte, error) {
	client := cfg.HttpClient()
	start := time.Now()
	relog := log.With("validate", "request-schema")
	relog.DebugContext(ctx, "request", "message", "fetch registry json schema", "start", start)
	resp, err := client.Get(ctx, "/registry/json-schema", nil)
	if err != nil {
		return nil, errors.New("unable to fetch Schema Spec")
	}
	relog.DebugContext(ctx, "request", "method", resp.Request.Method, "url", resp.Request.URL, "status", resp.Status, "duration", time.Since(start))
	defer resp.Body.Close()

	b, err := io.ReadAll(resp.Body)
	if err != nil {
		relog.DebugContext(ctx, "error", err)
		return nil, errors.New("unable to decode JSON Schema Spec")
	}
	return b, nil
}
